import { SCHEMA } from '../src/db/schema.ts';
import { ARCHIVE_OLD_AUDIT_DELETE, ARCHIVE_OLD_AUDIT_INSERT, auditArchiveCutoff } from '../src/lib/audit-archive.ts';
import { getPool, redactDatabaseUrl } from './pg.ts';
import { translateSqliteSchema } from './pg-schema.ts';

const STRUCTURAL_CATEGORIES = ['sugar', 'yeast', 'nutrients', 'barrels', 'bottles', 'botanicals', 'packaging', 'labels', 'other'];

export async function migrateDatabase(): Promise<void> {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        version TEXT PRIMARY KEY,
        applied_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
      )
    `);
    const existing = await client.query('SELECT version FROM schema_migrations WHERE version = $1', ['001']);
    if (existing.rowCount === 0) {
      await client.query(`
        CREATE TABLE IF NOT EXISTS users (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT NOT NULL,
          password_hash TEXT NOT NULL,
          name TEXT,
          role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('owner', 'admin', 'user')),
          status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
          approval_token TEXT UNIQUE,
          created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
        )
      `);
      await client.query('CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (lower(email))');
      await client.query(`
        CREATE TABLE IF NOT EXISTS user_permissions (
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          permission_key TEXT NOT NULL,
          PRIMARY KEY (user_id, permission_key)
        )
      `);
      await client.query(`
        CREATE TABLE IF NOT EXISTS user_process_assignments (
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          stage_key TEXT NOT NULL,
          PRIMARY KEY (user_id, stage_key)
        )
      `);
      await client.query(translateSqliteSchema(SCHEMA));
      await client.query(`
        CREATE TABLE IF NOT EXISTS production_meta (
          id INTEGER PRIMARY KEY CHECK (id = 1),
          revision BIGINT NOT NULL DEFAULT 0,
          updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
        )
      `);
      await client.query(`
        INSERT INTO production_meta (id, revision)
        VALUES (1, 0)
        ON CONFLICT (id) DO NOTHING
      `);
      await client.query(`
        CREATE TABLE IF NOT EXISTS production_row_revisions (
          table_name TEXT NOT NULL,
          row_id INTEGER NOT NULL,
          change_rev BIGINT NOT NULL,
          row_hash TEXT NOT NULL,
          PRIMARY KEY (table_name, row_id)
        )
      `);
      await client.query(`
        CREATE TABLE IF NOT EXISTS audit_events (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id INTEGER,
          email TEXT NOT NULL DEFAULT '',
          action TEXT NOT NULL,
          summary TEXT NOT NULL DEFAULT '',
          created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
        )
      `);
      await client.query('CREATE INDEX IF NOT EXISTS idx_audit_events_created ON audit_events (created_at)');
      for (const name of STRUCTURAL_CATEGORIES) {
        await client.query('INSERT INTO inventory_categories (name) VALUES ($1)', [name]);
      }
      await client.query(
        `INSERT INTO floor_plans (id, name, width_ft, height_ft, notes) VALUES (1, 'Production Floor', 80, 60, '')`,
      );
      await client.query(`SELECT setval(pg_get_serial_sequence('floor_plans', 'id'), 1, true)`);
      await client.query(`INSERT INTO schema_migrations (version) VALUES ('001')`);
    }
    const resetMigration = await client.query('SELECT version FROM schema_migrations WHERE version = $1', ['002']);
    if (resetMigration.rowCount === 0) {
      await client.query(`
        CREATE TABLE IF NOT EXISTS password_reset_tokens (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          token_hash TEXT NOT NULL UNIQUE,
          expires_at TEXT NOT NULL,
          created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
        )
      `);
      await client.query(`INSERT INTO schema_migrations (version) VALUES ('002')`);
    }
    const ownerMigration = await client.query('SELECT version FROM schema_migrations WHERE version = $1', ['003']);
    if (ownerMigration.rowCount === 0) {
      await client.query(`ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check`);
      await client.query(`ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('owner', 'admin', 'user'))`);
      await client.query(`
        UPDATE users
        SET role = 'owner', status = 'approved', approval_token = NULL
        WHERE lower(email) = 'nelson@rum.ky'
      `);
      await client.query(`INSERT INTO schema_migrations (version) VALUES ('003')`);
    }
    const auditArchiveMigration = await client.query('SELECT version FROM schema_migrations WHERE version = $1', ['004']);
    if (auditArchiveMigration.rowCount === 0) {
      await client.query(`
        CREATE TABLE IF NOT EXISTS audit_events_archive (
          id INTEGER PRIMARY KEY,
          user_id INTEGER,
          email TEXT NOT NULL DEFAULT '',
          action TEXT NOT NULL,
          summary TEXT NOT NULL DEFAULT '',
          created_at TEXT NOT NULL,
          archived_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
        )
      `);
      await client.query('CREATE INDEX IF NOT EXISTS idx_audit_events_archive_created ON audit_events_archive (created_at)');
      const cutoff = auditArchiveCutoff();
      await client.query(ARCHIVE_OLD_AUDIT_INSERT, [cutoff]);
      await client.query(ARCHIVE_OLD_AUDIT_DELETE, [cutoff]);
      await client.query(`INSERT INTO schema_migrations (version) VALUES ('004')`);
    }
    const bottlingLabelMigration = await client.query('SELECT version FROM schema_migrations WHERE version = $1', ['005']);
    if (bottlingLabelMigration.rowCount === 0) {
      await client.query(`ALTER TABLE bottling_run_lines ADD COLUMN IF NOT EXISTS packaging_label TEXT NOT NULL DEFAULT ''`);
      await client.query(`INSERT INTO schema_migrations (version) VALUES ('005')`);
    }
    await client.query(`
      INSERT INTO inventory_categories (name)
      SELECT 'botanicals'
      WHERE NOT EXISTS (
        SELECT 1 FROM inventory_categories WHERE lower(name) = 'botanicals'
      )
    `);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    const message = error instanceof Error ? error.message : 'Migration failed';
    throw new Error(redactDatabaseUrl(message));
  } finally {
    client.release();
  }
}
