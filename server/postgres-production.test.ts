function mockResponse() {
  const state = { statusCode: 200, body: null as unknown, res: {} as Response };
  state.res = {
    status(code: number) {
      state.statusCode = code;
      return state.res;
    },
    json(body: unknown) {
      state.body = body;
    },
  } as Response;
  return state;
}

