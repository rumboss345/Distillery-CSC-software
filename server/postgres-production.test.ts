describe('PostgreSQL connection rules', () => {
  it('uses SSL only for external Render URLs', () => {
    expect(postgresSsl('postgres://user:pass@dpg-abc-a/distillery')).toBeUndefined();
    expect(postgresSsl('postgres://user:pass@dpg-abc-a.oregon-postgres.render.com/distillery')).toEqual({
      rejectUnauthorized: false,
    });
    expect(postgresSsl('postgres://user:pass@db.internal/distillery?sslmode=require')).toEqual({
      rejectUnauthorized: false,
    });
    expect(postgresSsl('postgres://user:pass@db.internal/distillery?sslmode=disable')).toBeUndefined();
  });

  it('redacts database URLs from errors', () => {
    expect(redactDatabaseUrl('connect failed postgres://user:secret@host/db more')).toBe(
      'connect failed postgres://*** more',
    );
  });

  it('translates the SQLite schema without inserting rows', () => {
    const sql = translateSqliteSchema(SCHEMA);
    expect(sql).toContain('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(sql).not.toContain('AUTOINCREMENT');
    expect(sql).not.toContain('COLLATE');
    expect(sql).toContain('DEFERRABLE INITIALLY DEFERRED');
    expect(sql).toContain('CREATE UNIQUE INDEX IF NOT EXISTS recipes_name_lower');
    expect(sql.match(/CREATE TABLE IF NOT EXISTS warehouse_locations/g)).toHaveLength(1);
    expect(sql).not.toMatch(/INSERT\s+INTO/i);
  });

  it('refuses a whole SQLite upload when DATABASE_URL is set', () => {
    const previous = process.env.DATABASE_URL;
    process.env.DATABASE_URL = LOCAL_URL;
    try {
      const blocked = mockResponse();
      let nextCalled = false;
      blockSqliteWrite({} as never, blocked.res, (() => { nextCalled = true; }) as NextFunction);
      expect(nextCalled).toBe(false);
      expect(blocked.statusCode).toBe(409);
      expect(blocked.body).toEqual({ error: 'Production records are stored in PostgreSQL.' });
    } finally {
      restoreEnv(previous);
    }

    const open = mockResponse();
    let passed = false;
    blockSqliteWrite({} as never, open.res, (() => { passed = true; }) as NextFunction);
    expect(passed).toBe(true);
    expect(open.statusCode).toBe(200);
  });
});

