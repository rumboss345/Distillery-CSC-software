interface ForeignKey {
  table: string;
  column: string;
  refTable: string;
  refColumn: string;
  onDelete: string | null;
}

function splitTopLevel(source: string, separator: string): string[] {
  const parts: string[] = [];
  let current = '';
  let depth = 0;
  for (let i = 0; i < source.length; i += 1) {
    const char = source[i];
    if (char === '(') depth += 1;
    if (char === ')') depth = Math.max(0, depth - 1);
    if (char === separator && depth === 0) {
      parts.push(current);
      current = '';
      continue;
    }
    current += char;
  }
  if (current.trim()) parts.push(current);
  return parts;
}

function stripReferences(columnSql: string): { sql: string; fk: Omit<ForeignKey, 'table'> | null } {
  const match = columnSql.match(
    /\s+REFERENCES\s+(\w+)\s*\((\w+)\)(\s+ON\s+DELETE\s+(CASCADE|SET NULL|RESTRICT|NO ACTION))?/i,
  );
  if (!match || match.index == null) return { sql: columnSql.trim(), fk: null };
  const columnName = columnSql.slice(0, match.index).trim().split(/\s+/)[0];
  const sql = `${columnSql.slice(0, match.index)}${columnSql.slice(match.index + match[0].length)}`.trim();
  return {
    sql: sql.replace(/\s+,/, ',').replace(/\s+$/, ''),
    fk: {
      column: columnName,
      refTable: match[1],
      refColumn: match[2],
      onDelete: match[4] ? match[4].toUpperCase() : null,
    },
  };
}

/** Translate the browser SQLite schema into PostgreSQL tables. No data is inserted. */
export function translateSqliteSchema(schema: string): string {
  const normalized = schema
    .replace(/COLLATE\s+NOCASE/gi, '')
    .replace(/datetime\('now'\)/gi, "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');

  const statements = splitTopLevel(normalized, ';').map((part) => part.trim()).filter(Boolean);
  const tables: string[] = [];
  const indexes: string[] = [];
  const foreignKeys: ForeignKey[] = [];
  const seen = new Set<string>();

  for (const statement of statements) {
    const createTable = statement.match(/^CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)\s*\(([\s\S]*)\)$/i);
    if (createTable) {
      const table = createTable[1];
      if (seen.has(table)) continue;
      seen.add(table);
      const columns = splitTopLevel(createTable[2], ',').map((column) => {
        const stripped = stripReferences(column);
        if (stripped.fk) foreignKeys.push({ table, ...stripped.fk });
        const sql = stripped.sql.trim();
        const uniqueName = sql.match(/^(\w+)\s+TEXT\b[\s\S]*\bUNIQUE\b/i);
        if (uniqueName) {
          indexes.push(
            `CREATE UNIQUE INDEX IF NOT EXISTS ${table}_${uniqueName[1]}_lower ON ${table} (lower(${uniqueName[1]}))`,
          );
        }
        return sql;
      }).filter(Boolean);
      tables.push(`CREATE TABLE IF NOT EXISTS ${table} (\n  ${columns.join(',\n  ')}\n)`);
      continue;
    }
    if (/^CREATE\s+(UNIQUE\s+)?INDEX/i.test(statement)) {
      indexes.push(statement);
    }
  }

  const fkSql = foreignKeys.map((fk) => {
    const action = fk.onDelete ? ` ON DELETE ${fk.onDelete}` : '';
    return `ALTER TABLE ${fk.table} ADD CONSTRAINT ${fk.table}_${fk.column}_fkey FOREIGN KEY (${fk.column}) REFERENCES ${fk.refTable}(${fk.refColumn})${action} DEFERRABLE INITIALLY DEFERRED`;
  });

  return [...tables, ...indexes, ...fkSql].join(';\n') + ';\n';
}
